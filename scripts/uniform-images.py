# Turns the large uniform photos in /assets (named exactly like the uniforms in lib/catalog.ts,
# capitals ignored) into small WebP files in app/assets/uniforms and writes app/uniform-images.ts.
# The originals stay out of Git. Run after adding or replacing a photo:  python scripts/uniform-images.py
# Needs Python 3 with Pillow (pip install pillow).
import re, sys
from pathlib import Path
from statistics import median
from PIL import Image

root = Path(__file__).resolve().parent.parent
source, target = root / 'assets', root / 'app' / 'assets' / 'uniforms'
names = re.findall(r"\['([^']+)','(?:Nasional|Umum)'", (root / 'lib' / 'catalog.ts').read_text(encoding='utf-8'))
photos = {p.stem.lower(): p for p in source.glob('*') if p.suffix.lower() in ('.png', '.jpg', '.jpeg', '.webp')}
unknown = sorted(set(photos) - {n.lower() for n in names})
if unknown: sys.exit('Nama berkas tidak cocok dengan seragam mana pun: ' + ', '.join(unknown))
slug = lambda name: re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-')
RATIO = 4 / 5  # every picture uses the same portrait frame
SIZES = {'thumb': (112, 140), 'photo': (480, 600)}

def frame(path):
    image = Image.open(path).convert('RGB')
    w, h = image.size
    corners = [image.getpixel(p) for p in ((4, 4), (w - 5, 4), (4, h - 5), (w - 5, h - 5))]
    background = tuple(int(median(c[i] for c in corners)) for i in range(3))
    # Garment = pixels clearly different from the plain studio background.
    diff = Image.merge('RGB', [band.point(lambda v, b=b: 255 if abs(v - b) > 28 else 0) for band, b in zip(image.split(), background)])
    box = diff.convert('L').point(lambda v: 255 if v else 0).getbbox() or (0, 0, w, h)
    left, top, right, bottom = box
    margin = 0.07 * max(right - left, bottom - top)
    left, top, right, bottom = left - margin, top - margin, right + margin, bottom + margin
    cw, ch = right - left, bottom - top
    if cw / ch < RATIO: grow = ch * RATIO - cw; left, right = left - grow / 2, right + grow / 2
    else: grow = cw / RATIO - ch; top, bottom = top - grow / 2, bottom + grow / 2
    canvas = Image.new('RGB', (round(right - left), round(bottom - top)), background)
    canvas.paste(image, (round(-left), round(-top)))
    return canvas

target.mkdir(parents=True, exist_ok=True)
for old in target.glob('*.webp'): old.unlink()
imports, entries = [], []
for index, name in enumerate(names):
    path = photos.get(name.lower())
    if not path: print('Belum ada foto:', name); entries.append('null'); continue
    picture = frame(path)
    for kind, size in SIZES.items():
        picture.resize(size, Image.LANCZOS).save(target / f'{slug(name)}-{kind}.webp', 'WEBP', quality=80 if kind == 'photo' else 82, method=6)
        imports.append(f"import {kind}{index} from './assets/uniforms/{slug(name)}-{kind}.webp';")
    entries.append(f'{{photo:photo{index},thumb:thumb{index}}}')
module = ['// Generated by scripts/uniform-images.py from the photos in /assets. Do not edit by hand.', *imports,
          '// Same order as `uniforms` in lib/catalog.ts; null = no photo yet.',
          'export const uniformImages:({photo:string;thumb:string}|null)[]=[' + ','.join(entries) + '];', '']
(root / 'app' / 'uniform-images.ts').write_text('\r\n'.join(module), encoding='utf-8', newline='')
total = sum(p.stat().st_size for p in target.glob('*.webp'))
print(f'{len(names) - entries.count("null")} dari {len(names)} seragam memiliki foto - {total / 1024:.0f} KB')
